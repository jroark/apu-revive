import unittest

from apu import epm7064s


class RoutingTable(unittest.TestCase):
    def test_no_shared_places(self):
        self.assertEqual(epm7064s.check(), 173)

    def test_every_macrocell_and_usable_pin(self):
        self.assertEqual(sorted(epm7064s.MACROCELL), list(range(1, 65)))
        io = {4, 5, 6, 8, 9, 11, 12, 14, 16, 17, 18, 19, 20, 21, 24, 25, 26, 27, 28, 29, 31, 33, 34,
              36, 37, 39, 40, 41}
        self.assertEqual(set(epm7064s.PIN), io | {1, 2, 43, 44})      # JTAG pins 7 13 32 38 excluded

    def test_places_in_range(self):
        for table in (epm7064s.MACROCELL, epm7064s.PIN):
            for places in table.values():
                self.assertTrue(1 <= len(places) <= 2)
                for field, slot in places:
                    self.assertTrue(0 <= field < 36 and 0 <= slot < 8)
        self.assertEqual(epm7064s.field_fuse(4, 35, 7), 28992 + 8 * (36 * 3 + 35) + 7)


if __name__ == "__main__":
    unittest.main()


import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
QOUT = ROOT / "vendor/quartus-13.0sp1/out"


@unittest.skipUnless((QOUT / "x00" / "x00.pof").exists(), "Quartus probe outputs not present (vendor/, not in git)")
class FuseModelAgainstQuartus(unittest.TestCase):
    """Co-simulate Quartus-compiled EPM7064S POFs against their AHDL sources."""

    @classmethod
    def setUpClass(cls):
        sys.path.insert(0, str(ROOT / "tools"))
        from apu import daf, fusemap, maf
        k = ROOT / "vendor/maxplus2-10.2/7k"
        base = fusemap.FuseMap(daf.parse((k / "s7064044.daf").read_bytes()), maf.parse((k / "m7064s.maf").read_bytes()))
        cls.fm = epm7064s.FuseMap(base)

    def cosim(self, name, steps=300):
        from apu import pof
        from fusesim_check import cosim
        d = QOUT / name
        pins = {n: int(p) for p, n in re.findall(r"PIN_(\d+) -to (\S+)", (d / (name + ".qsf")).read_text())}
        fuses = pof.logical_fuses(pof.Pof.from_bytes((d / (name + ".pof")).read_bytes()))
        return cosim(name, (d / (name + ".tdf")).read_text(), None, self.fm, fuses, pins, steps=steps, verbose=False)

    def test_routing_probes(self):
        # combinational copies of input pins and of register feedbacks
        for name in ("x00", "x07", "x15", "y00", "y12", "z00", "z03"):
            if (QOUT / name / (name + ".pof")).exists():
                checks, mismatches = self.cosim(name)
                self.assertGreater(checks, 0)
                self.assertEqual(mismatches, [], name)


@unittest.skipUnless((ROOT / "vendor/maxplus2-10.2/7k/s7064044.daf").exists(), "MAX+PLUS II device files not present")
class GeneratedTriState(unittest.TestCase):
    """Tri-state outputs enabled from the OE pins, generated by our compiler and simulated."""

    def test_oe_pins_and_a_product_term_enable(self):
        import itertools
        import tempfile
        from apu import fusesim
        sys.path.insert(0, str(ROOT / "tools"))
        from gen_check7064s import build
        text = ("SUBDESIGN tri\n( a, b, g1, g2 : INPUT;\n  y1, y2, y3, y4 : OUTPUT; )\nBEGIN\n"
                "\ty1 = TRI(a, g1);\n\ty2 = TRI(b, !g2);\n\ty3 = TRI(a & b, g1);\n\ty4 = TRI(a, a & !b);\nEND;\n")
        with tempfile.TemporaryDirectory() as tmp:
            path = pathlib.Path(tmp) / "tri.tdf"
            path.write_text(text)
            _, _, base, fuses, fitted = build(path)
        pins = fitted.pins
        self.assertEqual({pins["g1"], pins["g2"]}, {44, 2})
        dev = fusesim.Device(epm7064s.FuseMap(base), fuses)
        mc = {p: m for m, p in base.pin_of.items()}
        for a, b, g1, g2 in itertools.product((0, 1), repeat=4):
            dev.set(**{"p%d" % pins[n]: v for n, v in (("a", a), ("b", b), ("g1", g1), ("g2", g2))})
            for y, en, val in (("y1", g1, a), ("y2", 1 - g2, b), ("y3", g1, a & b), ("y4", a & (1 - b), a)):
                self.assertEqual(bool(dev.driving(mc[pins[y]])), bool(en), (y, a, b, g1, g2))
                if en:
                    self.assertEqual(dev.pin_value(pins[y]), val, (y, a, b, g1, g2))
